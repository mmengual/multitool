import AppKit

/// Watches the general pasteboard and feeds the history, and writes items
/// back to it when the user picks one.
///
/// macOS sends no notification when the pasteboard changes, so we poll
/// `changeCount`: it is a cheap integer read.
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount = 0
    /// changeCount produced by our own writes, which must not be recorded again.
    private var ownChangeCount = -1

    /// Types that password managers and other apps use to say "don't keep this".
    /// See nspasteboard.org.
    private static let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Log.clipboard.info("monitor started")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        Log.clipboard.info("monitor stopped")
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount else { return }
        capture()
    }

    private func capture() {
        let settings = Settings.shared
        let types = Set(pasteboard.types ?? [])
        if settings.clipboardIgnoreSensitive, !types.isDisjoint(with: Self.sensitiveTypes) {
            Log.clipboard.info("skipped: marked sensitive")
            return
        }
        let source = NSWorkspace.shared.frontmostApplication
        if let id = source?.bundleIdentifier, settings.clipboardExcludedApps.contains(id) {
            Log.clipboard.info("skipped: excluded app \(id, privacy: .public)")
            return
        }

        let store = ClipboardStore.shared
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            store.addFiles(urls, source: source)
            return
        }
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            store.addText(text, rtf: pasteboard.data(forType: .rtf), source: source)
            return
        }
        if settings.clipboardCaptureImages,
           types.contains(.png) || types.contains(.tiff),
           let image = NSImage(pasteboard: pasteboard),
           let png = Self.pngData(image) {
            store.addImage(png: png, size: image.size, source: source)
        }
    }

    /// Puts an item back on the pasteboard. `plainText` drops rich formatting.
    func write(_ item: ClipboardItem, plainText: Bool = false) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            if !plainText, let rtf = item.rtf { pasteboard.setData(rtf, forType: .rtf) }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pasteboard.writeObjects(urls)
        case .image:
            if let url = ClipboardStore.shared.imageURL(for: item),
               let image = NSImage(contentsOf: url) {
                pasteboard.writeObjects([image])
            }
        }
        ownChangeCount = pasteboard.changeCount
        ClipboardStore.shared.touch(item)
    }

    private static func pngData(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
